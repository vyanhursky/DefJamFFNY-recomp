#!/usr/bin/env python3
"""Write src/patches/fighter_caf_layout.h from setup/fighter_caf_layout.py.

    python scripts/gen-fighter-caf-layout.py          rewrite the header
    python scripts/gen-fighter-caf-layout.py --check  exit 1 if the committed header is stale

The unit test tests/unit/test_fighter_caf_layout.py runs the check.
"""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / 'setup'))
import fighter_caf_layout as layout  # noqa: E402

TARGET = ROOT / 'src/patches/fighter_caf_layout.h'


def render():
    lines = [
        '/* Generated by scripts/gen-fighter-caf-layout.py from setup/fighter_caf_layout.py. Do not edit. */',
        '#ifndef DEFJAM_FIGHTER_CAF_LAYOUT_H',
        '#define DEFJAM_FIGHTER_CAF_LAYOUT_H',
        '',
        '#define CAF_CONTAINER_MAGIC "%s"' % layout.MAGIC.decode('ascii'),
        '#define CAF_CONTAINER_VERSION %du' % layout.VERSION,
        '#define CAF_CONTAINER_HEADER_BYTES %du' % layout.HEADER_BYTES,
        '#define CAF_CONTAINER_MAX_BYTES %du' % layout.MAX_FILE,
    ]
    # Header words follow the 4-byte magic and the 4-byte version.
    for index, name in enumerate(layout.HEADER):
        lines.append('#define CAF_HEADER_%s %du' % (name.upper(), 8 + 4 * index))
    lines += [
        '',
        '#define CAF_ROW_STRIDE %du' % layout.RECIPE_STRIDE,
        '#define CAF_ROW_VALUE_COUNT %du' % layout.VALUES,
        '#define CAF_ROW_COLOR_COUNT %du' % layout.COLORS,
        '#define CAF_ROW_TRAINING_COUNT %du' % layout.TRAINING,
        '#define CAF_ROW_STYLE_COUNT_MAX %du' % layout.STYLES,
    ]
    lines += ['#define CAF_ROW_%s %du' % (name.upper(), offset) for name, offset in layout.RECIPE.items()]
    lines += [
        '#define CAF_ROW_TRAINING_AT(i) (CAF_ROW_TRAINING + 4u * (i))',
        '#define CAF_ROW_VALUE_AT(i) (CAF_ROW_VALUES + 4u * (i))',
        '#define CAF_ROW_STYLE_AT(i) (CAF_ROW_STYLES + (i))',
        '',
        '#define CAF_EXTRA_STRIDE %du' % layout.EXTRA_STRIDE,
        '#define CAF_EXTRA_FINISHER_COUNT %du' % layout.FINISHERS,
        '#define CAF_EXTRA_ATLAS_COUNT %du' % layout.ATLASES,
        '#define CAF_ATLAS_BYTES %du' % layout.ATLAS_BYTES,
    ]
    lines += ['#define CAF_EXTRA_%s %du' % (name.upper(), offset) for name, offset in layout.EXTRA.items()]
    lines += [
        '#define CAF_EXTRA_FINISHER_AT(i) (CAF_EXTRA_FINISHERS + 4u * (i))',
        '#define CAF_EXTRA_ATLAS_AT(i) (CAF_EXTRA_ATLASES + 4u * (i))',
        '',
        '#define CAF_FACE_VERTEX_COUNT %du' % layout.FACE_VERTICES,
        '#define CAF_FACE_VERTEX_BYTES %du' % layout.FACE_VERTEX_BYTES,
        '#define CAF_FACE_VERTEX_DELTA %du' % layout.FACE_VERTEX_DELTA,
        '#define CAF_FACE_STRIDE %du' % layout.FACE_STRIDE,
        '#define CAF_FACE_BASIS_COUNT %du' % layout.BASIS,
    ]
    lines += ['#define CAF_FACE_%s %du' % (name.upper(), offset) for name, offset in layout.FACE.items()]
    lines += [
        '#define CAF_FACE_BASIS_AT(i) (CAF_FACE_BASIS + 4u * (i))',
        '#define CAF_FACE_VERTEX_AT(v) (CAF_FACE_VERTICES + CAF_FACE_VERTEX_BYTES * (v))',
        '',
        '#endif',
        '',
    ]
    return '\n'.join(lines)


def main(argv):
    text = render()
    if '--check' in argv:
        current = TARGET.read_bytes().decode('utf-8').replace('\r\n', '\n') if TARGET.exists() else ''
        if current != text:
            print('src/patches/fighter_caf_layout.h is stale; run python scripts/gen-fighter-caf-layout.py', file=sys.stderr)
            return 1
        return 0
    TARGET.write_bytes(text.encode('utf-8'))
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
